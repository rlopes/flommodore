const testing = std.testing;

test "flsnd: A4 is $028E, the value the Phase 4 register test uses" {
    try testing.expectEqual(@as(u16, 0x028E), noteReg(a4_index));
    try testing.expectEqual(@as(u16, 654), noteReg(a4_index));
    // …and the octaves either side are exact doublings of it, give or take
    // one LSB of rounding.
    try testing.expectEqual(@as(u16, 327), noteReg(a4_index - 12));
    try testing.expectEqual(@as(u16, 1308), noteReg(a4_index + 12));
}

test "flsnd: the table is monotonic and spans the audible range" {
    var prev: u16 = 0;
    var i: u32 = 0;
    while (i < note_count) : (i += 1) {
        const r = noteReg(i);
        try testing.expect(r > prev); // strictly rising: no two notes collide
        prev = r;
    }
    try testing.expectEqual(@as(u16, 24), noteReg(0)); // C0 ~16.35 Hz
    try testing.expectEqual(@as(u16, 5872), noteReg(95)); // B7 ~3951 Hz
    // Nyquist at rate 0 is $8000; the top note must sit far below it.
    try testing.expect(noteReg(95) < 0x8000 / 4);
}

test "flsnd: tuning error is bounded, and concentrated in the bottom octaves" {
    // The whole table is within a quarter tone…
    try testing.expect(worstCents() < 25.0);
    // …but that error lives at the bottom: from C2 up nothing exceeds
    // 4 cents, which is inaudible.
    var i: u32 = 24; // C2
    while (i < note_count) : (i += 1) {
        try testing.expect(@abs(centsError(i)) < 4.0);
    }
    // C0 is the coarse one: one LSB there spans most of a semitone, which
    // is why sndlib documents C0-C1 as tempered rather than accurate.
    try testing.expect(centsPerLsb(0) > 60.0);
    try testing.expect(centsPerLsb(a4_index) < 3.0);
}

test "flsnd: generated source carries the table and its own provenance" {
    var buf: [64 * 1024]u8 = undefined;
    var w = std.Io.Writer.fixed(&buf);
    try writeNoteTable(&w);
    const out = w.buffered();
    try testing.expect(std.mem.indexOf(u8, out, "GENERATED by `flsnd notes`") != null);
    try testing.expect(std.mem.indexOf(u8, out, "note_table:") != null);
    try testing.expect(std.mem.indexOf(u8, out, "DW $028E") != null); // A4
    try testing.expect(std.mem.indexOf(u8, out, "EQU NOTE_A4, 57") != null);
    // One DW per note, no more.
    var count: u32 = 0;
    var it = std.mem.splitScalar(u8, out, '\n');
    while (it.next()) |line| {
        if (std.mem.startsWith(u8, line, "    DW ")) count += 1;
    }
    try testing.expectEqual(note_count, count);
}

test "flsnd: bank validation rejects what it should" {
    var img: [header_size + patch_size]u8 = @splat(0);
    img[0] = 'F';
    img[1] = 'S';
    std.mem.writeInt(u16, img[2..4], 1, .little);
    img[4] = 1; // one patch
    try (Bank{ .bytes = &img }).check();

    var bad = img;
    bad[1] = 'X';
    try testing.expectError(Error.NotFlsnd, (Bank{ .bytes = &bad }).check());

    var wrong_ver = img;
    std.mem.writeInt(u16, wrong_ver[2..4], 2, .little);
    try testing.expectError(Error.BadVersion, (Bank{ .bytes = &wrong_ver }).check());

    var too_many = img;
    too_many[4] = 33;
    try testing.expectError(Error.TooManyPatches, (Bank{ .bytes = &too_many }).check());

    // Truncated: the header claims a patch the file does not contain.
    try testing.expectError(Error.BadImage, (Bank{ .bytes = img[0..header_size] }).check());
}

test "flsnd: patch names are space-padded on disk, trimmed on the way out" {
    var img: [header_size + patch_size]u8 = @splat(0);
    img[0] = 'F';
    img[1] = 'S';
    std.mem.writeInt(u16, img[2..4], 1, .little);
    img[4] = 1;
    const name_at = header_size + p_name;
    @memset(img[name_at..][0..16], ' ');
    @memcpy(img[name_at..][0..4], "BASS");
    const bank = Bank{ .bytes = &img };
    try bank.check();
    try testing.expectEqualStrings("BASS", bank.patchName(0));
    // An all-space name trims to empty rather than underflowing.
    @memset(img[name_at..][0..16], ' ');
    try testing.expectEqualStrings("", bank.patchName(0));
}
